    def load_config(self):
        frontend_config_path = Path(__file__).resolve().parents[1] / "config" / "frontend.json"
        if frontend_config_path.exists():
            try:
                with open(frontend_config_path, 'r', encoding='utf-8') as f:
                    fe_cfg = json.load(f)
                    self.language = fe_cfg.get("language", "zh")
            except Exception as e:
                logger.warning(f"Failed to load language config: {e}")

    def save_config(self):
        frontend_config_path = Path(__file__).resolve().parents[1] / "config" / "frontend.json"
        fe_cfg = {}
        if frontend_config_path.exists():
            try:
                with open(frontend_config_path, 'r', encoding='utf-8') as f:
                    fe_cfg = json.load(f)
            except Exception:
                pass
        
        fe_cfg["language"] = self.language
        try:
            with open(frontend_config_path, 'w', encoding='utf-8') as f:
                json.dump(fe_cfg, f, ensure_ascii=False, indent=2)
        except Exception as e:
            logger.error(f"Failed to save language config: {e}")

    def tr(self, key: str) -> str:
        return self.translations.get(self.language, self.translations["zh"]).get(key, key)

    def set_language(self, lang: str):
        if lang in self.translations:
            self.language = lang
            self.save_config()

